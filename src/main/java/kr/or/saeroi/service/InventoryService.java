package kr.or.saeroi.service;

import java.util.List;

import kr.or.saeroi.dto.InventoryDTO;

/**
 * 재고 관리 Service 인터페이스
 * 
 * 역할:
 * - Controller 와 DAO 연결
 * - 비즈니스 로직 처리
 * - 재고 CRUD 처리
 */
public interface InventoryService {

	// =========================================================================
	// 재고 목록 조회
	// 검색 + 페이징 처리
	// =========================================================================
	public List<InventoryDTO> getInventoryList(

			String searchType,
			String keyword,
			String startDate,
			String endDate);

	// =========================================================================
	// 품목 목록 조회
	// 등록 모달 select 출력용
	// =========================================================================
	public List<InventoryDTO> getItemList();

	// =========================================================================
	// 품목 선택 시 창고 위치 조회
	// AJAX 자동입력용
	// =========================================================================
	public String getStockLocationByItemId(
			int itemId);

	// =========================================================================
	// 재고 등록
	// =========================================================================
	public int addInventory(
			InventoryDTO dto);

	// =========================================================================
	// 재고 상세조회
	// inventoryDetail.jsp 출력용
	// =========================================================================
	public InventoryDTO getInventoryDetail(
			int inventoryId);

	// =========================================================================
	// 재고 선택 삭제
	// 체크박스 다중 삭제
	// =========================================================================
	public int removeInventory(
			String[] inventoryIds);

	// =========================================================================
	// 재고 상세페이지 입출고 내역 조회
	// 재고번호 기준으로 해당 품목의 입고 / 사용 / 출고 이력을 조회한다.
	// =========================================================================
	public List<InventoryDTO> getInventoryInoutHistoryList(
			int inventoryId);

	// =========================================================================
	// 재고 수정
	// =========================================================================
	public int modifyInventory(
			InventoryDTO dto);

}
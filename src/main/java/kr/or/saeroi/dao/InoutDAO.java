package kr.or.saeroi.dao;

import java.util.List;

import kr.or.saeroi.dto.InoutDTO;

// =============================================================
// 입출고 DAO 인터페이스
// 자재 입출고 목록 / 등록 / 상세 / 수정 / 삭제 SQL 작업 이름을 정의한다.
// =============================================================
public interface InoutDAO {

	// =============================================================
	// 기존 코드 호환용 목록 조회
	// 검색어에 입고 / 출고가 들어왔을 때도 처리하기 위해 유지한다.
	// =============================================================
	public List<InoutDTO> selectInoutList(
			String searchType,
			String keyword,
			String startDate,
			String endDate);

	// =============================================================
	// 입출고구분 검색 포함 목록 조회
	// =============================================================
	public List<InoutDTO> selectInoutList(
			String searchType,
			String inoutType,
			String keyword,
			String startDate,
			String endDate);

	// =============================================================
	// 전체 개수 조회
	// =============================================================
	public int selectInoutCount(
			String searchType,
			String inoutType,
			String keyword,
			String startDate,
			String endDate);

	// =============================================================
	// 등록 모달 품목 목록 조회
	// 품목 선택 시 거래처명 / 담당자 / 현재재고 / 창고위치 자동 표시용 데이터 포함
	// =============================================================
	public List<InoutDTO> selectItemList();

	// =============================================================
	// 품목 선택 시 자동 표시할 품목 상세 정보 조회
	// 거래처명 / 담당자 / 현재재고 대표값 조회용
	// =============================================================
	public InoutDTO selectItemInfo(int itemId);

	// =============================================================
	// 품목 선택 시 자동 표시할 품목 상세 정보 조회
	// 입출고구분까지 받아서 입고는 공급처, 출고는 납품처 기준으로 조회한다.
	// =============================================================
	public InoutDTO selectItemInfo(
			int itemId,
			String inoutType);

	// =============================================================
	// 품목별 창고위치 목록 조회
	// 창고위치 select 박스 출력용
	// =============================================================
	public List<InoutDTO> selectStockLocationList(int itemId);

	// =============================================================
	// 출고 선택 시 품목별 LOT 목록 조회
	// 입고된 LOT 중 현재 남아있는 LOT만 select 박스에 출력한다.
	// =============================================================
	public List<InoutDTO> selectMaterialLotList(int itemId);

	// =============================================================
	// 입출고 등록
	// =============================================================
	public int insertInout(InoutDTO dto);

	// =============================================================
	// 입출고 상세 조회
	// =============================================================
	public InoutDTO selectInoutDetail(int inoutId);

	// =============================================================
	// 입출고 선택 삭제
	// =============================================================
	public int deleteInout(String[] inoutIds);

	// =============================================================
	// 입출고 수정
	// =============================================================
	public int updateInout(InoutDTO dto);
}

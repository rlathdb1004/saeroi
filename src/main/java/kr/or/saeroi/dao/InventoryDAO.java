package kr.or.saeroi.dao;

import java.util.List;

import kr.or.saeroi.dto.InventoryDTO;

/**
 * 재고 관리 DAO 인터페이스
 * 
 * 역할:
 * - 재고 목록 조회
 * - 재고 등록
 * - 재고 수정
 * - 재고 삭제
 * - 재고 상세조회
 * - 품목 조회
 * - 창고 위치 조회
 */
public interface InventoryDAO {

	// =========================================================================
	// 재고 목록 조회
	// 검색 + 페이징 처리용
	// =========================================================================
	public List<InventoryDTO> selectInventoryList(

			String searchType,
			String keyword,
			String startDate,
			String endDate);

	// =========================================================================
	// 품목 목록 조회
	// 등록 모달 select 출력용
	// =========================================================================
	public List<InventoryDTO> selectItemList();

	// =========================================================================
	// 품목 선택 시 창고 위치 조회
	// AJAX 자동입력용
	// =========================================================================
	public String getStockLocationByItemId(
			int itemId);

	// =========================================================================
	// 재고 등록
	// =========================================================================
	public int insertInventory(
			InventoryDTO dto);

	// =========================================================================
	// 재고 상세조회
	// inventoryDetail.jsp 출력용
	// =========================================================================
	public InventoryDTO selectInventoryDetail(
			int inventoryId);

	// =========================================================================
	// 재고 선택 삭제
	// 체크박스 여러개 삭제
	// =========================================================================
	public int deleteInventory(
			String[] inventoryIds);

	// =========================================================================
	// 재고 수정
	// =========================================================================
	public int updateInventory(
			InventoryDTO dto);

}